import 'dart:convert';
import 'dart:io';

import 'package:macro_kit/src/core/core.dart';
import 'package:path/path.dart' as p;

/// An asset macro that watches shader sources and rebuilds Flutter GPU shader bundles.
///
/// Whenever a file inside the watched shader directory changes (add, modify or
/// remove), this macro locates every `*.shaderbundle.json` manifest in that
/// directory, resolves the shader source paths declared by the manifest, and
/// re-runs `impellerc` to produce a compiled `.shaderbundle`.
///
/// The compiled bundles are written into the configured asset macro output
/// directory (for example `build/shaderbundles`), so a running Flutter app can
/// pick up rebuilt shaders on hot reload/restart without any manual build step.
///
/// ## How it finds `impellerc`
///
/// Mirrors the runtime discovery used by shader hot-reload examples:
///
/// 1. [ShaderReloaderConfig.compilerPath] explicit override
/// 2. [ShaderReloaderConfig.flutterRoot] explicit override
/// 3. `FLUTTER_ROOT` environment variable
/// 4. `FLUTTER_ROOT=` inside the project's platform-specific ephemeral config
///    generated by the flutter tool (`Flutter-Generated.xcconfig` on macOS/iOS,
///    `generated_config.cmake` on Linux/Windows)
///
/// For each candidate root it probes the engine artifacts directory
/// `bin/cache/artifacts/engine/<target>/impellerc` where `<target>` matches
/// the host machine's Flutter tooling (darwin-arm64/darwin-x64 on macOS,
/// linux-x64 on Linux, windows-x64 on Windows), and also passes the engine's
/// `shader_lib` directory via `--include`.
///
/// ## Usage
///
/// ```dart
/// await runMacro(
///   macros: {
///     'ShaderReloaderMacro': ShaderReloaderMacro.initialize,
///   },
///   assetMacros: {
///     'shaders': [
///       AssetMacroInfo(
///         macroName: 'ShaderReloaderMacro',
///         // The server matches single-level extensions, so `.json`
///         // also covers `.shaderbundle.json` manifests.
///         extension: '.vert,.frag,.json',
///         output: 'build/shaderbundles',
///         config: const ShaderReloaderConfig().toJson(),
///       ),
///     ],
///   },
/// );
/// ```
class ShaderReloaderMacro extends MacroGenerator {
  const ShaderReloaderMacro({
    super.capability = const MacroCapability(),
    this.config = const ShaderReloaderConfig(),
  });

  /// Initialize macro for execution
  static ShaderReloaderMacro initialize(MacroConfig config) {
    final key = config.key;
    final props = key.propertiesAsMap();

    return ShaderReloaderMacro(
      capability: config.capability,
      config: Macro.parseMacroConfig(
        value: props['config']?.constantValue,
        fn: ShaderReloaderConfig.fromJson,
        defaultValue: const ShaderReloaderConfig(),
      ),
    );
  }

  /// The shader bundle configuration
  final ShaderReloaderConfig config;

  @override
  String get suffixName => '';

  @override
  GeneratedType get generatedType => GeneratedType.clazz;

  @override
  Future<void> onAsset(MacroState state, MacroAssetDeclaration asset) async {
    final assetState = state.assetState;
    if (assetState == null) return;

    final entity = FileSystemEntity.typeSync(assetState.absoluteBasePath, followLinks: false);
    if (entity != FileSystemEntityType.directory) return;

    final manifests = _findManifests(Directory(assetState.absoluteBasePath));
    if (manifests.isEmpty) return;

    final projectRoot = _resolveProjectRoot(assetState);
    final compiler = _findCompiler(projectRoot);
    if (compiler == null) {
      throw StateError(
        'ShaderReloaderMacro could not find impellerc. '
        "Set ShaderReloaderConfig(compilerPath: ...) or ShaderReloaderConfig(flutterRoot: ...), "
        'or define the FLUTTER_ROOT environment variable pointing to your Flutter SDK.',
      );
    }

    state.set('projectRoot', projectRoot);
    state.set('compilerPath', compiler.path);
    state.set('manifests', manifests);
  }

  @override
  Future<void> onGenerate(MacroState state) async {
    final manifests = state.getOrNull<List<ShaderBundleManifest>>('manifests');
    if (manifests == null || manifests.isEmpty) return;

    final projectRoot = state.getOrNull<String>('projectRoot') ?? '';
    final compilerPath = state.getOrNull<String>('compilerPath') ?? '';
    final outputPath = state.assetState!.absoluteBaseOutputPath;
    final shaderLibraryDirectory = Directory(compilerPath).uri.resolve('./shader_lib');

    final generatedFiles = <String>[];
    for (final manifest in manifests) {
      final outputFile = File(p.join(outputPath, manifest.relativeDir, manifest.outputFileName));
      await outputFile.parent.create(recursive: true);

      final result = await Process.run(compilerPath, [
        '--sl=${outputFile.path}',
        '--shader-bundle=${json.encode(manifest.entries)}',
        '--include=${shaderLibraryDirectory.toFilePath()}',
      ], workingDirectory: projectRoot);

      if (result.exitCode != 0) {
        throw StateError(
          'impellerc failed for "${manifest.sourcePath}" '
          '(exit code ${result.exitCode}):\n${'${result.stderr}\n${result.stdout}'.trim()}',
        );
      }

      generatedFiles.add(outputFile.path);
    }

    state.reportGeneratedFile(generatedFiles);
  }

  /// Collects and prepares all `*.shaderbundle.json` manifests inside [dir].
  ///
  /// Relative `file` entries are resolved to absolute paths against the
  /// manifest's own directory, exactly like the runtime hot-reload flow does.
  List<ShaderBundleManifest> _findManifests(Directory dir) {
    final manifestExtension = config.manifestExtension ?? '.shaderbundle.json';
    final manifests = <ShaderBundleManifest>[];

    for (final entity in dir.listSync(recursive: true, followLinks: false)) {
      if (entity is! File) continue;
      if (!p.basename(entity.path).endsWith(manifestExtension)) continue;

      final Object? decoded;
      try {
        decoded = jsonDecode(entity.readAsStringSync());
      } catch (_) {
        throw StateError('ShaderReloaderMacro failed to parse manifest: ${entity.path}');
      }
      if (decoded is! Map<String, dynamic>) {
        throw StateError(
          'ShaderReloaderMacro expected a JSON object in manifest: ${entity.path}',
        );
      }

      final entries = decoded;
      final manifestDirectory = entity.parent;
      for (final entry in entries.values) {
        if (entry is Map<String, dynamic> && entry['file'] is String) {
          entry['file'] = manifestDirectory.uri.resolve(entry['file'] as String).toFilePath();
        }
      }

      // `foo.shaderbundle.json` -> `foo.shaderbundle`
      var baseName = p.basenameWithoutExtension(p.basenameWithoutExtension(entity.path));
      if (!baseName.endsWith('.shaderbundle')) baseName = '$baseName.shaderbundle';

      final relativeDir = p.relative(manifestDirectory.path, from: dir.path);

      manifests.add(ShaderBundleManifest(
        sourcePath: entity.path,
        relativeDir: relativeDir == '.' ? '' : relativeDir,
        outputFileName: baseName,
        entries: entries,
      ));
    }

    return manifests;
  }

  /// Derives the enclosing project root from the watched asset directory by
  /// walking up one level per segment of the relative asset path.
  String _resolveProjectRoot(AssetState assetState) {
    final depth = p.split(p.normalize(assetState.relativeBasePath)).length;
    var root = p.normalize(assetState.absoluteBasePath);
    for (var i = 0; i < depth; i++) {
      root = p.dirname(root);
    }
    return root;
  }

  /// Locates `impellerc` using, in order of precedence: the explicit compiler
  /// path override, the flutter root overrides, the `FLUTTER_ROOT` environment
  /// variable, and finally the platform-specific ephemeral config generated by
  /// the flutter tool inside the project.
  File? _findCompiler(String projectRoot) {
    if (config.compilerPath?.isNotEmpty == true) {
      final candidate = File(config.compilerPath!);
      if (candidate.existsSync()) return candidate.absolute;
    }

    final flutterRoots = <String>[
      if (config.flutterRoot?.isNotEmpty == true) config.flutterRoot!,
      ?Platform.environment['FLUTTER_ROOT'],
    ];

    const xcconfigKey = 'FLUTTER_ROOT=';
    const cmakeKey = 'set(FLUTTER_ROOT';
    for (final line in _readEphemeralConfigLines(projectRoot)) {
      // Xcode style (macOS/iOS): FLUTTER_ROOT=/path/to/flutter
      if (line.startsWith(xcconfigKey)) {
        flutterRoots.add(line.substring(xcconfigKey.length));
        break;
      }
      // CMake style (Linux/Windows): set(FLUTTER_ROOT "/path/to/flutter")
      if (line.startsWith(cmakeKey)) {
        final value = line.substring(cmakeKey.length).replaceAll(')', '').trim();
        if (value.startsWith('"') && value.endsWith('"') && value.length >= 2) {
          flutterRoots.add(value.substring(1, value.length - 1));
        } else if (value.isNotEmpty) {
          flutterRoots.add(value);
        }
        break;
      }
    }

    for (final root in flutterRoots) {
      final engineArtifacts = Directory(root).uri.resolve('bin/cache/artifacts/engine/');
      for (final location in const [
        'darwin-arm64/impellerc',
        'darwin-x64/impellerc',
        'linux-x64/impellerc',
        'windows-x64/impellerc.exe',
      ]) {
        final candidate = File.fromUri(engineArtifacts.resolve(location));
        if (candidate.existsSync()) return candidate;
      }
    }
    return null;
  }

  /// Yields all lines of the platform-specific ephemeral config files that the
  /// flutter tool generates inside a project, in probing order.
  Iterable<String> _readEphemeralConfigLines(String projectRoot) sync* {
    for (final relativePath in [
      p.join('macos', 'Flutter', 'ephemeral', 'Flutter-Generated.xcconfig'),
      p.join('ios', 'Flutter', 'ephemeral', 'Flutter-Generated.xcconfig'),
      p.join('linux', 'flutter', 'ephemeral', 'generated_config.cmake'),
      p.join('windows', 'flutter', 'ephemeral', 'generated_config.cmake'),
    ]) {
      final file = File(p.join(projectRoot, relativePath));
      if (file.existsSync()) {
        yield* file.readAsLinesSync();
      }
    }
  }
}

/// A parsed `*.shaderbundle.json` manifest with its shader source paths
/// already resolved to absolute paths.
class ShaderBundleManifest {
  const ShaderBundleManifest({
    required this.sourcePath,
    required this.relativeDir,
    required this.outputFileName,
    required this.entries,
  });

  /// Absolute path of the manifest json file
  final String sourcePath;

  /// Directory of the manifest relative to the watched shader directory
  /// (empty string when the manifest sits at its root).
  ///
  /// Preserved under the output directory so nested manifests don't clash.
  final String relativeDir;

  /// Output file name, e.g. `flutter_example.shaderbundle`
  final String outputFileName;

  /// Decoded manifest with `file` values resolved to absolute paths
  final Map<String, dynamic> entries;
}

/// Configuration for the shader reload macro.
class ShaderReloaderConfig {
  const ShaderReloaderConfig({
    this.manifestExtension,
    this.compilerPath,
    this.flutterRoot,
  });

  static ShaderReloaderConfig fromJson(Map<String, dynamic> json) {
    return ShaderReloaderConfig(
      manifestExtension: json['manifestExtension'] as String?,
      compilerPath: json['compilerPath'] as String?,
      flutterRoot: json['flutterRoot'] as String?,
    );
  }

  /// Suffix that identifies shader bundle manifests within the watched
  /// directory.
  ///
  /// Default is `.shaderbundle.json`
  final String? manifestExtension;

  /// Explicit path to the `impellerc` executable.
  ///
  /// When set, it takes precedence over all automatic discovery strategies.
  final String? compilerPath;

  /// Explicit path to the Flutter SDK root used to locate `impellerc` and the
  /// engine `shader_lib` includes.
  ///
  /// Takes precedence over `FLUTTER_ROOT` and `Flutter-Generated.xcconfig`.
  final String? flutterRoot;

  Map<String, dynamic> toJson() {
    return {
      if (manifestExtension?.isNotEmpty == true) 'manifestExtension': manifestExtension,
      if (compilerPath?.isNotEmpty == true) 'compilerPath': compilerPath,
      if (flutterRoot?.isNotEmpty == true) 'flutterRoot': flutterRoot,
    };
  }

  @override
  String toString() {
    return 'ShaderReloaderConfig{manifestExtension: $manifestExtension, compilerPath: $compilerPath, flutterRoot: $flutterRoot}';
  }
}
